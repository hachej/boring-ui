/**
 * Environment-sensitive browser capabilities, in one place. Browsers expose `crypto.randomUUID`, `crypto.subtle`,
 * `navigator.clipboard` and `navigator.share` only in secure contexts (HTTPS, localhost); a page served over plain HTTP on a
 * private network gets none of them. Every browser-reachable package and the studio import these instead of the raw APIs,
 * and `npm run check` (scripts/check-platform-apis.mjs) fails when browser-reachable source uses a raw one.
 */

/** A version 4 UUID; falls back to `crypto.getRandomValues`, which every context has. */
export function randomUUID(): string {
  const crypto = globalThis.crypto;
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6]! & 0x0f) | 0x40;
  bytes[8] = (bytes[8]! & 0x3f) | 0x80;
  const hex = Array.from(bytes, byte => byte.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/**
 * Puts `text` on the clipboard: the async Clipboard API where present, otherwise a hidden-textarea `execCommand('copy')`
 * (works over plain HTTP). Resolves `false` when neither worked, so the caller can show the text for a manual copy.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  try { const clipboard = globalThis.navigator?.clipboard; if (clipboard) { await clipboard.writeText(text); return true; } }
  catch { /* denied or unfocused: try the selection route */ }
  const doc = globalThis.document;
  if (!doc?.body || typeof doc.execCommand !== 'function') return false;
  const area = doc.createElement('textarea');
  area.value = text;
  area.setAttribute('readonly', '');
  area.style.cssText = 'position:fixed;top:0;left:0;width:1px;height:1px;opacity:0;pointer-events:none';
  const focus = doc.activeElement instanceof HTMLElement ? doc.activeElement : undefined;
  doc.body.append(area);
  try { area.select(); area.setSelectionRange(0, text.length); return doc.execCommand('copy'); }
  catch { return false; }
  finally { area.remove(); focus?.focus({ preventScroll: true }); }
}

/** SHA-256 of `bytes`; without `crypto.subtle` it uses the portable standard (FIPS 180-4) implementation below, with identical output. */
export async function sha256(bytes: Uint8Array<ArrayBuffer>): Promise<Uint8Array> {
  const subtle = globalThis.crypto?.subtle;
  if (subtle) return new Uint8Array(await subtle.digest('SHA-256', bytes));
  return sha256Portable(bytes);
}

/** SHA-1 of `bytes` (a content identifier, not a security boundary): `crypto.subtle` where present, otherwise the portable implementation below. */
export async function sha1(bytes: Uint8Array<ArrayBuffer>): Promise<Uint8Array> {
  const subtle = globalThis.crypto?.subtle;
  if (subtle) return new Uint8Array(await subtle.digest('SHA-1', bytes));
  return sha1Portable(bytes);
}

/** Exported for the equivalence check only; use `sha1`. */
export function sha1Portable(bytes: Uint8Array): Uint8Array {
  const length = bytes.length, blocks = Math.ceil((length + 9) / 64);
  const padded = new Uint8Array(blocks * 64);
  padded.set(bytes);
  padded[length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor(length / 0x20000000));
  view.setUint32(padded.length - 4, (length * 8) >>> 0);
  const h = Uint32Array.from([0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476, 0xc3d2e1f0]);
  const w = new Uint32Array(80);
  const rotl = (x: number, n: number) => (x << n) | (x >>> (32 - n));
  for (let offset = 0; offset < padded.length; offset += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getUint32(offset + i * 4);
    for (let i = 16; i < 80; i++) w[i] = rotl(w[i - 3]! ^ w[i - 8]! ^ w[i - 14]! ^ w[i - 16]!, 1);
    let [a, b, c, d, e] = [h[0]!, h[1]!, h[2]!, h[3]!, h[4]!];
    for (let i = 0; i < 80; i++) {
      const f = i < 20 ? (b & c) | (~b & d) : i < 40 ? b ^ c ^ d : i < 60 ? (b & c) | (b & d) | (c & d) : b ^ c ^ d;
      const k = i < 20 ? 0x5a827999 : i < 40 ? 0x6ed9eba1 : i < 60 ? 0x8f1bbcdc : 0xca62c1d6;
      const t = (rotl(a, 5) + f + e + k + w[i]!) >>> 0;
      e = d; d = c; c = rotl(b, 30) >>> 0; b = a; a = t;
    }
    h[0] = (h[0]! + a) >>> 0; h[1] = (h[1]! + b) >>> 0; h[2] = (h[2]! + c) >>> 0; h[3] = (h[3]! + d) >>> 0; h[4] = (h[4]! + e) >>> 0;
  }
  const out = new Uint8Array(20), outView = new DataView(out.buffer);
  h.forEach((word, i) => outView.setUint32(i * 4, word));
  return out;
}

