import { readFile, writeFile } from "node:fs/promises"
import { resolve } from "node:path"
import process from "node:process"
import ts from "typescript"

const cliRoot = resolve(import.meta.dirname, "..")
const workspaceDist = resolve(cliRoot, "../workspace/dist")
const generatedPath = resolve(cliRoot, "src/server/pluginFrontRuntime/workspaceSingletonExports.generated.ts")

const entrypoints = [
  ["WORKSPACE_ROOT_SINGLETON_EXPORTS", "workspace.js"],
  ["WORKSPACE_PLUGIN_SINGLETON_EXPORTS", "plugin.js"],
  ["WORKSPACE_EVENTS_SINGLETON_EXPORTS", "events.js"],
]

function exportedNames(source, fileName) {
  const sourceFile = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const names = new Set()

  for (const statement of sourceFile.statements) {
    if (ts.isExportDeclaration(statement)) {
      if (!statement.exportClause || !ts.isNamedExports(statement.exportClause)) {
        throw new Error(`${fileName} contains an unsupported star export`)
      }
      for (const element of statement.exportClause.elements) names.add(element.name.text)
      continue
    }

    const isExported = statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
    if (!isExported || !statement.name || !ts.isIdentifier(statement.name)) continue
    names.add(statement.name.text)
  }

  names.delete("default")
  return [...names].sort()
}

function render(entries) {
  const lines = [
    "// Generated by scripts/generate-host-singleton-exports.mjs from @hachej/boring-workspace build outputs.",
    "// Do not edit by hand; run `pnpm run generate:singleton-exports` after changing workspace exports.",
    "",
  ]
  for (const [constant, names] of entries) {
    lines.push(`export const ${constant} = ${JSON.stringify(names, null, 2)} as const`, "")
  }
  return lines.join("\n")
}

const entries = await Promise.all(entrypoints.map(async ([constant, fileName]) => {
  const source = await readFile(resolve(workspaceDist, fileName), "utf8")
  return [constant, exportedNames(source, fileName)]
}))
const expected = render(entries)

if (process.argv.includes("--check")) {
  const actual = await readFile(generatedPath, "utf8").catch(() => "")
  if (actual !== expected) {
    throw new Error("workspace singleton export metadata is stale; run `pnpm run generate:singleton-exports`")
  }
} else {
  await writeFile(generatedPath, expected)
}
