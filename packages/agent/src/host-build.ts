import { mkdtemp, readdir, readFile, realpath, rename, rm, rmdir, stat, writeFile } from 'node:fs/promises';
import { isAbsolute, join, posix, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import type { HostBuild } from './host/contract.js';
import { defineApp, type AppDefinition } from './host/define-app.js';
import { entry } from './host-cloudflare/entry.js';

/** `entry(specifier(appDir, flag))` is the text of `.gen/server.ts` for an `--options` flag: what a caller compares the written file with. */
export { entry, specifier };

const STALE_MS = 10 * 60 * 1000;
const GEN = '// generated by boring-host-build: the same text for every build of this app\n';
const first = (error: unknown) => String(error instanceof Error ? error.message : error).split('\n')[0]!;
const isFile = (path: string) => stat(path).then((s) => s.isFile(), () => false);
const isPath = (module: string) => isAbsolute(module) || /^\.\.?\//.test(module);
/** One rule for every path flag: `./x` and `../x` are relative to the app folder, an absolute path is rewritten relative to `.gen/`, a package name or an alias is kept. */
const specifier = (dir: string, module: string) => {
  if (isAbsolute(module)) { const path = relative(resolve(dir, '.gen'), module).split(sep).join('/'); return path.startsWith('.') ? path : `./${path}`; }
  return isPath(module) ? `../${posix.normalize(module)}` : module;
};
const checked = async (dir: string, flag: string, module: string) => {
  if (isPath(module) && !(await isFile(resolve(dir, module)))) throw new Error(`${flag}: ${module} is not a file`);
  if (!isPath(module) && (await isFile(resolve(dir, module)))) throw new Error(`${flag}: ${module} is a file in the app folder, write ./${module} (a package name is copied as given)`);
  return specifier(dir, module);
};
const inside = async (dir: string, path: string) => { const root = await realpath(dir), real = await realpath(path); return real === root || real.startsWith(root + sep); };

/** The folders of `path` (links followed), sorted; one that leaves the app folder is refused, never skipped. */
async function folders(dir: string, path: string) {
  const out: string[] = [];
  for (const name of (await readdir(path)).sort()) {
    if (!(await stat(join(path, name)).then((s) => s.isDirectory(), () => false))) continue;
    if (!(await inside(dir, join(path, name)))) throw new Error(`${relative(dir, join(path, name))} is outside the app folder`);
    out.push(name);
  }
  return out;
}

/** `<app>/<skills>/<agent>/<skill>/SKILL.md` as `agent -> "skills/<skill>/SKILL.md" -> text`, both levels sorted, nothing from outside the app folder. */
async function skillTexts(dir: string, def: AppDefinition) {
  const out: Record<string, Record<string, string>> = {};
  if (!def.skills) return out;
  try {
    if (isAbsolute(def.skills)) throw new Error(`${def.skills} is an absolute path, write it relative to the app folder`);
    const root = join(dir, def.skills);
    if (!(await inside(dir, root))) throw new Error(`${def.skills} is outside the app folder`);
    for (const agent of await folders(dir, root)) for (const skill of await folders(dir, join(root, agent))) {
      const file = join(root, agent, skill, 'SKILL.md');
      if (!(await inside(dir, file))) throw new Error(`${agent}/${skill}/SKILL.md is outside the app folder`);
      (out[agent] ??= {})[`skills/${skill}/SKILL.md`] = await readFile(file, 'utf8');
    }
  } catch (error) { throw new Error(`skills: ${first(error)}`); }
  return out;
}

/** Removes this tool's own leftovers beside `.gen/` (a killed build's `.gen.tmp-*` and `.gen.old-*`) once they are older than STALE_MS. Best effort; nothing else is touched. */
async function sweep(dir: string) {
  for (const name of await readdir(dir)) {
    if (!/^\.gen\.(tmp|old)-[A-Za-z0-9]+$/.test(name)) continue;
    const info = await stat(join(dir, name)).catch(() => undefined);
    if (info?.isDirectory() && Date.now() - info.mtimeMs > STALE_MS) await rm(join(dir, name), { recursive: true, force: true }).catch(() => {});
  }
}

/** Reads the app's `app.ts` and replaces `.gen/` beside it. Everything is checked before the first write, and the files are written to `.gen.tmp` first. */
export const hostBuild: HostBuild = async (appDir, flags) => {
  if (!flags.options) throw new Error('--options <module> is required (the mount options of the stack)');
  const dir = resolve(appDir);
  if (!(await stat(dir).then((s) => s.isDirectory(), () => false))) throw new Error(`${appDir}: no such folder`);
  if (!(await isFile(join(dir, 'app.ts')))) throw new Error(`app.ts: no such file in ${appDir}`);
  const options = await checked(dir, '--options', flags.options);
  const shell = await checked(dir, '--shell', flags.shell ?? '@/components/app-host');
  const stack = flags.stack ? await checked(dir, '--stack', flags.stack) : undefined;
  if (flags.page && !(await isFile(resolve(dir, flags.page)))) throw new Error(`--page: ${flags.page} is not a file`);
  let def: AppDefinition;
  // The app's own definition, the same file the Worker bundles: the one computed import() of this file (SELF-2's named exception). It runs with the caller's rights.
  try { def = defineApp((await import(pathToFileURL(join(dir, 'app.ts')).href)).default); } catch (error) { throw new Error(`app.ts: ${first(error)}`); }
  for (const view of def.views) {
    if (!(await isFile(join(dir, view.component)))) throw new Error(`views.${view.id}.component: ${view.component} is not a file`);
    if (!(await inside(dir, join(dir, view.component)))) throw new Error(`views.${view.id}.component: ${view.component} is outside the app folder`);
  }
  const skills = await skillTexts(dir, def);
  const page = flags.page ? await readFile(resolve(dir, flags.page), 'utf8') : '';
  const views = def.views.map((view, i) => ({ id: view.id, name: `View${i}`, from: `../${posix.normalize(view.component)}` }));
  const files: Record<string, string> = {
    'server.ts': entry(options),
    'assets.ts': `${GEN}import type { Assets } from "@hachej/boring-agent/host";\n\nconst assets: Assets = ${JSON.stringify({ page, skills })};\n\nexport default assets;\n`,
    'page.tsx': `${GEN}import { createRoot } from "react-dom/client";\nimport { AppHost } from ${JSON.stringify(shell)};\n${views.map((v) => `import ${v.name} from ${JSON.stringify(v.from)};\n`).join('')}\n`
      + `createRoot(document.getElementById("root")!).render(<AppHost name=${JSON.stringify(def.name)} languages={${JSON.stringify(def.languages)}} views={[${views.map((v) => `{ id: ${JSON.stringify(v.id)}, component: ${v.name} }`).join(', ')}]} />);\n`,
    ...(stack ? { 'alchemy.run.ts': `import def from "../app.ts";\nimport Worker from "./server.ts";\nimport { appStack } from ${JSON.stringify(stack)};\n\nexport default appStack(def, Worker);\n` } : {}),
  };
  await sweep(dir);
  const gen = join(dir, '.gen'), tmp = await mkdtemp(join(dir, '.gen.tmp-')), old = await mkdtemp(join(dir, '.gen.old-'));
  try {
    for (const [name, text] of Object.entries(files)) await writeFile(join(tmp, name), text);
    await rename(gen, old).catch((error) => { if (error.code !== 'ENOENT') throw error; });
    await rename(tmp, gen);
    await rm(old, { recursive: true, force: true }).catch((error) => { throw new Error(`the new .gen is in place, but its old copy ${old} could not be removed: ${first(error)}`); });
  } finally {
    await rm(tmp, { recursive: true, force: true });
    await rmdir(old).catch(() => {});
  }
};
