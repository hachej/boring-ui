// Regenerate after upgrading the pinned Tailwind dependency or changing the registry theme bindings.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const tailwind = dirname(fileURLToPath(import.meta.resolve('tailwindcss/package.json')));
const registry = JSON.parse(readFileSync(new URL('../../registry.json', import.meta.url), 'utf8'));
const bindings = registry.items.find(item => item.name === 'theme').cssVars.theme;
const sources = Object.fromEntries(['theme', 'preflight', 'utilities'].map(name => [name, readFileSync(join(tailwind, `${name}.css`), 'utf8')]));
sources.bindings = `@theme inline { ${Object.entries(bindings).map(([name, value]) => `--${name}: ${value};`).join('\n')} }`;
const license = readFileSync(join(tailwind, 'LICENSE'), 'utf8');
const output = new URL('./mockup-tailwind.ts', import.meta.url);
const text = `// Generated by build-tailwind.mjs from tailwindcss@4.3.3 and registry.json.\n/* ${license} */\nexport const sources = ${JSON.stringify(sources, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== text) throw new Error('Regenerate mockup-tailwind.ts with build-tailwind.mjs');
} else writeFileSync(output, text);
