// Every kit CircleIcon is a filled status/recording dot. Phosphor's regular circle is a
// path outline, so SVG fill/strokeWidth (used by existing callers) cannot fill its centre.
// Keep the native SVG props and ref, while allowing an explicit native weight override.
export const CircleIcon = forwardRef<SVGSVGElement, IconProps>((props, ref) =>
  createElement(PhosphorCircle, { weight: 'fill', ...props, ref }));
