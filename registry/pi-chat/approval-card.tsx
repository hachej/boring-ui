'use client';

import { useEffect, useRef, useState } from 'react';
import type { ToolCall, ToolResultMessage } from '@earendil-works/pi-ai';
import { CheckIcon, ShieldAlertIcon, XIcon } from 'lucide-react';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Item, ItemActions, ItemContent, ItemDescription, ItemFooter, ItemMedia, ItemTitle } from '@/components/ui/item';
import type { AnswerOutcome } from './question-card';
import { useChatText } from './labels';

// The strings `requireApproval` (`@hachej/boring-agent/approval`) asks with and puts at the start of a denial result.
export const APPROVE = 'Approve';
export const DENY = 'Deny';
export const DENIED_PREFIX = 'Denied by the person.';


/** The arguments the call would run with, one line each. They come from the model's call itself: the card shows what will actually execute. */
export function describeArguments(call: ToolCall): { readonly name: string; readonly value: string }[] {
  return Object.entries(call.arguments as Record<string, unknown>).map(([name, value]) => {
    const text = typeof value === 'string' ? value : JSON.stringify(value) ?? '';
    return { name, value: text.length > 600 ? `${text.slice(0, 600)}…` : text };
  });
}

/**
 * The settled state. The wrapper records its decision in the call's details; a call that settled without one was never
 * decided (the run was stopped while it waited), so it is not shown as approved.
 */
function decisionOf(result: ToolResultMessage | undefined, decision: 'approved' | 'denied' | 'cancelled' | undefined): 'pending' | 'denied' | 'approved' | 'cancelled' {
  if (!result) return 'pending';
  if (decision) return decision;
  const text = result.content.map(part => part.type === 'text' ? part.text : '').join('');
  return result.isError && text.startsWith(DENIED_PREFIX) ? 'denied' : 'cancelled';
}

/** Human approval for a gated tool call: pending (Approve and Deny), then approved or denied. Answering uses the host's `answer`. */
export function ApprovalCard({ call, result, answer, questionId, summary, decision, live = false }: {
  readonly call: ToolCall;
  /** The question ID bound to this call's assistant entry (`derive` provides it); answers use it, never the bare call ID. */
  readonly questionId?: string | undefined;
  /** The decision `requireApproval` recorded in the call's details (`derive` finds it). Without one, a settled call shows as not decided. */
  readonly decision?: 'approved' | 'denied' | 'cancelled' | undefined;
  /** The one-line summary `requireApproval` published for this call (`derive` finds it). Shown first; the raw arguments are then collapsed under it. */
  readonly summary?: string | undefined;
  readonly result: ToolResultMessage | undefined;
  readonly answer?: ((callId: string, answer: string) => Promise<AnswerOutcome>) | undefined;
  /** The call is still being generated by the model: it cannot be decided yet. */
  readonly live?: boolean;
}) {
  const { labels } = useChatText();
  const [sent, setSent] = useState<string | undefined>();
  const [sending, setSending] = useState<string | undefined>();
  const [refusal, setRefusal] = useState<string | undefined>();
  const mounted = useRef(true);
  useEffect(() => { mounted.current = true; return () => { mounted.current = false; }; }, []);
  const settled = decisionOf(result, decision);
  // `pending` means the decision waits on the person; `writing` means the model is still generating the call.
  const state = settled !== 'pending' ? settled : sent === APPROVE ? 'approved-sent' : sent === DENY ? 'denied-sent' : live ? 'writing' : 'pending';
  const open = state === 'pending' || state === 'writing';
  const args = describeArguments(call);
  const busy = sending !== undefined || live;

  async function decide(value: string) {
    if (!answer || !questionId || busy) return;
    setRefusal(undefined); setSending(value);
    try {
      const outcome = await answer(questionId, value);
      if (outcome.kind === 'answered') setSent(value);
      else setRefusal(outcome.reason || labels.decisionRefused(outcome.kind));
    } catch (cause) { setRefusal(cause instanceof Error ? cause.message : labels.decisionNotSent); }
    finally { if (mounted.current) setSending(undefined); }
  }
  const approved = state === 'approved' || state === 'approved-sent', denied = state === 'denied' || state === 'denied-sent';

  const status = open ? labels.needsApproval : approved ? labels.approved : denied ? labels.denied : labels.notDecided;
  const unavailable = !answer || !questionId || busy;

  // shadcn's Confirmation recipe: an outline Item with the question and Approve/Deny actions; pending approvals are prompts, not activity.
  return <Item variant="outline" size="sm" render={<section />} data-testid="approval-card" data-state={state} data-call-id={call.id} data-tool={call.name} aria-label={labels.approvalNeeded} className="my-2">
    <ItemMedia variant="icon">
      {approved ? <CheckIcon aria-hidden="true" /> : denied ? <XIcon aria-hidden="true" /> : <ShieldAlertIcon aria-hidden="true" />}
    </ItemMedia>
    <ItemContent>
      <ItemDescription className="line-clamp-none"><Badge variant={open ? 'outline' : denied ? 'destructive' : 'secondary'}>{status}</Badge></ItemDescription>
      {summary && <ItemTitle data-testid="approval-summary" className="line-clamp-none [overflow-wrap:anywhere]">{summary}</ItemTitle>}
      <ItemDescription data-testid="approval-tool" className="line-clamp-none [overflow-wrap:anywhere]">{labels.wantsToRun} <code className="font-mono">{call.name}</code></ItemDescription>
      {args.length > 0 && (() => {
        const list = <dl data-testid="approval-args" className="m-0 grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 text-xs">
          {args.map(item => [<dt key={`${item.name}:n`} className="text-muted-foreground">{item.name}</dt>, <dd key={`${item.name}:v`} className="m-0 font-mono whitespace-pre-wrap [overflow-wrap:anywhere]">{item.value}</dd>])}
        </dl>;
        // With a summary the raw arguments are the detail behind it; without one they are all the person has to decide on.
        return summary ? <details data-testid="approval-details" className="text-xs"><summary className="inline-flex min-h-8 cursor-pointer items-center text-muted-foreground select-none max-sm:min-h-11 pointer-coarse:min-h-11">{labels.arguments}</summary>{list}</details> : list;
      })()}
    </ItemContent>
    {open && <ItemActions role="group" aria-label={labels.decision}>
      <Button variant="default" data-testid="approval-approve" disabled={unavailable} onClick={() => { void decide(APPROVE); }}><CheckIcon data-icon="inline-start" aria-hidden="true" />{labels.approve}</Button>
      <Button variant="outline" data-testid="approval-deny" disabled={unavailable} onClick={() => { void decide(DENY); }}><XIcon data-icon="inline-start" aria-hidden="true" />{labels.deny}</Button>
    </ItemActions>}
    {(open && (live || !answer || !questionId)) && <ItemFooter><ItemDescription>{live ? labels.stillWritingCall : labels.decidingUnavailable}</ItemDescription></ItemFooter>}
    {(state === 'approved-sent' || state === 'denied-sent') && <ItemFooter><ItemDescription>{labels.decisionSent(approved)}</ItemDescription></ItemFooter>}
    {refusal && open && <ItemFooter><p role="alert" data-testid="approval-refusal" className="m-0 text-sm text-destructive">{refusal}</p></ItemFooter>}
  </Item>;
}
