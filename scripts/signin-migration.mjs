// Derives the kit's sign-in migration from Better Auth's own `getMigrations` output (so it cannot be written by hand and drift), and writes it.
//   node scripts/signin-migration.mjs --write     rewrites packages/ui/src/signin/migration-sql.ts (then `npm run build`)
// test/packages/signin-migration.test.mjs imports `deriveSignInMigration` and fails when the shipped SQL differs from what this derives.
// It needs a built tree (dist/signin) and the optional peers (better-auth).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { getMigrations } from 'better-auth/db/migration';

/** Better Auth's DDL for a fresh database, every create made IF NOT EXISTS, one statement per paragraph. */
export async function deriveSignInMigration(options = {}) {
  const { signIn } = await import('@hachej/boring-ui-kit/signin');
  const { countingD1, resetSignInCaches } = await import('@hachej/boring-ui-kit/signin/testing');
  resetSignInCaches();
  const { auth } = signIn({ database: countingD1().database, secret: 'derive-'.repeat(8), origin: 'https://derive.fictional.test', appName: 'Derive', ...options });
  const sql = await (await getMigrations(auth.options)).compileMigrations();
  const statements = sql.split(/;\s*\n/).map((s) => s.trim().replace(/;$/, '')).filter(Boolean)
    .map((s) => s.replace(/^create (unique )?(table|index) (?!if not exists)/i, (_, unique, kind) => `create ${unique ?? ''}${kind} if not exists `));
  return statements.map((s) => `${s};`).join('\n\n') + '\n';
}

/** The options that add tables or indexes (Google, Studio link, provider): the same SQL for all of them is part of what the test asserts. */
export const FULL_OPTIONS = { provider: true, google: { clientId: 'client', clientSecret: 'secret' }, studio: { origin: 'https://studio.fictional.test', app: 'app', clientId: 'client' } };

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] && process.argv.includes('--write')) {
  const sql = await deriveSignInMigration(FULL_OPTIONS);
  const body = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  writeFileSync(new URL('../packages/ui/src/signin/migration-sql.ts', import.meta.url),
    `// GENERATED by scripts/signin-migration.mjs --write from Better Auth's getMigrations: do not edit (test/packages/signin-migration.test.mjs fails on drift).\nexport const signInMigrationSql: string = \`${body}\`;\n`);
  console.log('wrote packages/ui/src/signin/migration-sql.ts');
}
