// The official diagrams.net viewer, vendored and pinned (D-1398). `node scripts/vendor-drawio-viewer.mjs` downloads
// `viewer-static.min.js` from jgraph/drawio at DRAWIO_TAG, refuses a file whose sha256 is not DRAWIO_SHA256, and writes it as one string
// constant into packages/ui/src/vendor/drawio-viewer-static.ts, which the kit exports as `@hachej/boring-ui-kit/drawio-viewer`. The drawing
// viewer block loads that subpath only when a draw.io file opens and runs it inside a sandboxed frame with no network: nothing is fetched
// from diagrams.net at runtime. `--check` verifies the committed file against the pin without downloading.
// Changing the version: set DRAWIO_TAG and DRAWIO_SHA256 (the sha256 of the new viewer-static.min.js), run this script, commit both.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const DRAWIO_TAG = 'v32.4.1';
export const DRAWIO_SHA256 = 'bc7586cb62eec98018c13b78619078d3a7179cc7bfc711c566dda19527520a30';
const target = fileURLToPath(new URL('../packages/ui/src/vendor/drawio-viewer-static.ts', import.meta.url));
const url = `https://raw.githubusercontent.com/jgraph/drawio/${DRAWIO_TAG}/src/main/webapp/js/viewer-static.min.js`;
const sha = text => createHash('sha256').update(text, 'utf8').digest('hex');

/** The generated module: a header naming the source and licence, then the script as a JSON string. */
export function vendoredModule(script) {
  return `// Generated by scripts/vendor-drawio-viewer.mjs: do not edit. The official diagrams.net viewer (viewer-static.min.js) of
// jgraph/drawio ${DRAWIO_TAG}, sha256 ${DRAWIO_SHA256}, Apache License 2.0 (https://github.com/jgraph/drawio/blob/${DRAWIO_TAG}/LICENSE).
// It bundles DOMPurify (Apache-2.0 or MPL-2.0), pako (MIT and Zlib) and others under the notices kept inside the script.
/** The viewer's script text, run only inside the drawing viewer's sandboxed frame. */
export const DRAWIO_VIEWER_SCRIPT: string = ${JSON.stringify(script)};
`;
}

/** The script text of the committed module (the JSON string after the constant's name). */
export function committedScript() {
  const text = readFileSync(target, 'utf8');
  const start = text.indexOf('= "');
  if (start < 0) throw new Error(`${target} has no script constant`);
  return JSON.parse(text.slice(start + 2, text.lastIndexOf(';')));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const script = committedScript();
    if (sha(script) !== DRAWIO_SHA256) throw new Error(`the vendored draw.io viewer is not ${DRAWIO_TAG} (sha256 ${sha(script)})`);
    console.log(`vendored draw.io viewer ${DRAWIO_TAG} matches its pin`);
  } else {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    const script = await response.text();
    if (sha(script) !== DRAWIO_SHA256) throw new Error(`${url} is not the pinned file (sha256 ${sha(script)})`);
    writeFileSync(target, vendoredModule(script));
    console.log(`wrote ${target} (${script.length} characters)`);
  }
}
