// Compiles the registry's blocks and the shadcn primitives into the kit's package, so an app imports them instead of copying them:
//   registry/<item>/<file>  -> packages/ui/dist/blocks/<item>/<file>.js (+ .d.ts)   @hachej/boring-ui-kit/blocks/<item>/<file>
//   shadcn/ui/<name>.tsx    -> packages/ui/dist/ui/<name>.js (+ .d.ts)              @hachej/boring-ui-kit/ui/<name>
//   every item's `css`      -> packages/ui/styles/blocks.css                        @hachej/boring-ui-kit/blocks.css
// One output file per source file, so a block's `lazy(() => import(...))` stays a split point in the app's bundle. Runs after tsc: blocks
// import the kit's other entries by package name.
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const walk = (directory) => readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(join(directory, entry.name)) : [join(directory, entry.name)]);
const isSource = (path) => /\.tsx?$/.test(path) && !path.endsWith('.d.ts') && !/\.test\.tsx?$/.test(path);

/** Where a source module lands under dist/, or null when the specifier is not one of ours. */
export function moduleTarget(spec) {
  const local = /^@\/(?:components\/ui|hooks)\/(.+)$/.exec(spec);
  if (local) return `ui/${local[1]}`;
  const block = /^@\/components\/(.+)$/.exec(spec);
  return block ? `blocks/${block[1]}` : null;
}

/** A compiled file's module specifiers made relative to dist/, with the explicit extension native ESM and every bundler accept. */
export function rewriteSpecifiers(text, file, dist) {
  const here = posix.dirname(file);
  const resolveFile = (path) => {
    const bare = path.replace(/\.(?:tsx?|jsx?)$/, '');
    if (existsSync(join(dist, `${bare}.js`))) return `${bare}.js`;
    if (existsSync(join(dist, bare, 'index.js'))) return `${bare}/index.js`;
    throw new Error(`${file}: "${path}" does not resolve in the compiled kit`);
  };
  const rewrite = (spec) => {
    const target = moduleTarget(spec);
    if (!target && !spec.startsWith('.')) return spec;
    const found = resolveFile(target ?? posix.join(here, spec));
    const next = posix.relative(here, found);
    return next.startsWith('.') ? next : `./${next}`;
  };
  // Comments keep their examples: a doc comment's `import('./my-view')` names the reader's file, not one of ours.
  return text.split('\n').map(line => /^\s*(?:\*|\/\/|\/\*)/.test(line) ? line : line.replace(/((?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)["'])((?:@\/|\.{1,2}\/)[^"'\n]+)(["'])/g, (_, before, spec, after) => `${before}${rewrite(spec)}${after}`)).join('\n');
}

/** The stylesheet import a block carries for its copied form: blocks.css already holds that sheet. */
const stripStylesheetImports = (text) => text.replace(/^import\s+["']@hachej\/boring-ui-kit\/[^"']+\.css["'];?\s*$/gm, '');

const merge = (target, source) => {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === 'object' && target[key] && typeof target[key] === 'object') merge(target[key], value);
    else target[key] = value && typeof value === 'object' ? merge({}, value) : value;
  }
  return target;
};
const serialize = (rules, indent = '') => Object.entries(rules).map(([key, value]) => {
  if (value && typeof value === 'object') return `${indent}${key} {\n${serialize(value, `${indent}  `)}\n${indent}}`;
  return value === '' ? `${indent}${key};` : `${indent}${key}: ${value};`;
}).join('\n');

/** Every registry item's CSS, in registry order, merged as the shadcn CLI merges it into an app's index.css. */
export function blocksCss(root) {
  const { items } = JSON.parse(readFileSync(join(root, 'registry.json'), 'utf8'));
  const merged = {};
  for (const item of items) if (item.css) merge(merged, item.css);
  const fileTree = readFileSync(join(root, 'packages/ui/styles/file-tree.css'), 'utf8');
  return `/* Generated by scripts/build-blocks.mjs: the CSS of every registry block. Import it after tailwindcss. */\n${serialize(merged)}\n${fileTree}`;
}

export function buildBlocks(root) {
  const ts = createRequire(join(root, 'package.json'))('typescript');
  const dist = join(root, 'packages/ui/dist');
  const stage = join(dist, '.blocks-stage');
  const { items } = JSON.parse(readFileSync(join(root, 'registry.json'), 'utf8'));
  const blockFiles = items.flatMap(item => (item.files ?? []).map(file => join(root, file.path))).filter(path => isSource(path) && existsSync(path));
  const roots = [...new Set(blockFiles), ...walk(join(root, 'shadcn')).filter(isSource)];
  const options = {
    rootDir: root, outDir: stage, baseUrl: root, declaration: true, jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler,
    target: ts.ScriptTarget.ES2022, lib: ['lib.es2023.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'], skipLibCheck: true, esModuleInterop: true, allowArbitraryExtensions: true, strict: true, types: ['node'], resolveJsonModule: true,
    paths: { '@/components/ui/*': ['shadcn/ui/*'], '@/hooks/*': ['shadcn/ui/*'], '@/components/*': ['registry/*'] },
  };
  const program = ts.createProgram(roots, options);
  const errors = ts.getPreEmitDiagnostics(program).concat(program.emit().diagnostics).filter(d => d.category === ts.DiagnosticCategory.Error);
  if (errors.length) throw new Error(`Blocks do not compile:\n${ts.formatDiagnostics(errors.slice(0, 40), { getCanonicalFileName: f => f, getCurrentDirectory: () => root, getNewLine: () => '\n' })}`);
  for (const [from, to] of [['registry', 'blocks'], ['shadcn/ui', 'ui']]) {
    rmSync(join(dist, to), { recursive: true, force: true });
    mkdirSync(dirname(join(dist, to)), { recursive: true });
    renameSync(join(stage, from), join(dist, to));
  }
  rmSync(stage, { recursive: true, force: true });
  for (const top of ['blocks', 'ui']) for (const path of walk(join(dist, top))) {
    if (!/\.(?:js|d\.ts)$/.test(path)) { rmSync(path); continue; }
    const file = relative(dist, path).split('\\').join('/');
    writeFileSync(path, rewriteSpecifiers(stripStylesheetImports(readFileSync(path, 'utf8')), file, dist));
  }
  writeFileSync(join(root, 'packages/ui/styles/blocks.css'), blocksCss(root));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildBlocks(fileURLToPath(new URL('../', import.meta.url)));
  console.log('Built the kit\'s compiled blocks');
}
