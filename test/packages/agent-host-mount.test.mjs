// host-mount-build: `boring-host-build` writes an app's `.gen/` (Worker entry, assets, page entry, optional stack entry) as the same text everywhere.
// The tests run the built command on copies of the two fixture apps, placed inside the repository's ignored `.cache/` so Node resolves their imports.
import assert from 'node:assert/strict';
import test from 'node:test';
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = fileURLToPath(new URL('../../', import.meta.url));
const cli = join(root, 'packages/agent/dist/host-build-cli.js');
const cache = join(root, '.cache');
mkdirSync(cache, { recursive: true });
const scratch = mkdtempSync(join(cache, 'host-mount-build-'));
test.after(() => rmSync(scratch, { recursive: true, force: true }));

const copy = (app, at) => { const dir = join(scratch, at, app); cpSync(join(root, 'fixtures/host-apps', app), dir, { recursive: true }); return dir; };
const build = (dir, ...flags) => spawnSync(process.execPath, [cli, dir, ...flags], { encoding: 'utf8', cwd: dir });
const gen = (dir) => Object.fromEntries(readdirSync(join(dir, '.gen')).sort().map((f) => [f, readFileSync(join(dir, '.gen', f), 'utf8')]));
const full = ['--shell', '@/components/app-host', '--options', './options.ts', '--stack', '@boring/stack'];

const SERVER = `// generated by boring-host-build: the same text for every app
import { Harness } from "@earendil-works/pi-durable";
import { mountApp } from "@hachej/boring-agent/host-cloudflare";
import def from "../app.ts";
import assets from "./assets.ts";
import options from "../options.ts";

export default mountApp(def, assets, { ...options, main: import.meta.url, openHarness: (storage, opts, context) => Harness.open(storage, opts, context) });
`;

test('build: two runs and two checkouts give the same text, and the same server entry for both apps', () => {
  const a = copy('todo', 'one'), b = copy('todo', 'deep/er/two'), n = copy('notes', 'one');
  for (const dir of [a, b, n]) { const r = build(dir, ...full); assert.equal(r.status, 0, r.stderr); }
  const first = gen(a), notes = gen(n);
  assert.deepEqual(Object.keys(first), ['alchemy.run.ts', 'assets.ts', 'page.tsx', 'server.ts']);
  assert.equal(build(a, ...full).status, 0);
  assert.deepEqual(gen(a), first, 'a second run in the same folder');
  assert.deepEqual(gen(b), first, 'the same app at another absolute path');
  assert.equal(first['server.ts'], SERVER);
  assert.equal(notes['server.ts'], SERVER, 'the notes app');
  assert.equal(first['alchemy.run.ts'], 'import def from "../app.ts";\nimport Worker from "./server.ts";\nimport { appStack } from "@boring/stack";\n\nexport default appStack(def, Worker);\n');
  for (const [file, text] of [...Object.entries(first), ...Object.entries(notes)]) {
    assert.ok(!text.includes(scratch) && !text.includes(root), `${file}: no absolute path`);
    assert.doesNotMatch(text, /\d{4}-\d\d-\d\d|\/home\//, file);
    const out = ts.transpileModule(text, { reportDiagnostics: true, fileName: file, compilerOptions: { jsx: ts.JsxEmit.Preserve } });
    assert.deepEqual(out.diagnostics, [], file);
  }
});

test('build: the page entry names the views, and the assets hold the skills in sorted order and the page text', () => {
  const n = copy('notes', 'assets');
  writeFileSync(join(n, 'page.html'), '<!doctype html><p>page</p>');
  assert.equal(build(n, ...full, '--page', 'page.html').status, 0);
  const files = gen(n);
  assert.match(files['page.tsx'], /import \{ AppHost \} from "@\/components\/app-host";/);
  assert.match(files['page.tsx'], /import View0 from "\.\.\/web\/NotesView\.tsx";/);
  assert.match(files['page.tsx'], /name="notes"/);
  const assets = JSON.parse(files['assets.ts'].match(/const assets: Assets = (.*);\n/)[1]);
  assert.equal(assets.page, '<!doctype html><p>page</p>');
  assert.deepEqual(Object.keys(assets.skills), ['assistant']);
  assert.deepEqual(Object.keys(assets.skills.assistant), ['skills/rappel/SKILL.md', 'skills/resume/SKILL.md']);
  assert.equal(assets.skills.assistant['skills/rappel/SKILL.md'], readFileSync(join(n, 'skills/assistant/rappel/SKILL.md'), 'utf8'));
  const without = copy('todo', 'no-page');
  assert.equal(build(without, '--options', './options.ts').status, 0);
  assert.equal(existsSync(join(without, '.gen/alchemy.run.ts')), false, 'no stack entry without --stack');
  assert.match(gen(without)['assets.ts'], /"page":""/);
  assert.match(gen(without)['page.tsx'], /@\/components\/app-host/);
});

test('build: --options is required, and nothing is written without it', () => {
  const dir = copy('todo', 'options');
  const r = build(dir);
  assert.equal(r.status, 1);
  assert.equal(r.stderr, 'boring-host-build: --options <module> is required (the mount options of the stack)\n');
  assert.equal(existsSync(join(dir, '.gen')), false);
});

test('broken folder: a refused app is one line, exit 1, and .gen stays as it was', () => {
  const broken = {
    'no app.ts': (dir) => rmSync(join(dir, 'app.ts')),
    'defineApp refuses': (dir) => writeFileSync(join(dir, 'app.ts'), readFileSync(join(dir, 'app.ts'), 'utf8').replace('name: "todo"', 'name: "Bad Name"')),
    'a view names no file': (dir) => rmSync(join(dir, 'web/TodosView.tsx')),
  };
  const wanted = { 'no app.ts': /app\.ts/, 'defineApp refuses': /name: lowercase/, 'a view names no file': /views\.todos\.component/ };
  for (const [name, spoil] of Object.entries(broken)) {
    for (const before of [false, true]) {
      const dir = copy('todo', `broken/${name.replace(/\W/g, '-')}-${before}`);
      if (before) { mkdirSync(join(dir, '.gen')); writeFileSync(join(dir, '.gen/server.ts'), 'old\n'); }
      spoil(dir);
      const r = build(dir, '--options', './options.ts', '--stack', '@boring/stack');
      assert.equal(r.status, 1, name);
      assert.match(r.stderr, /^boring-host-build: .*\n$/, name);
      assert.match(r.stderr, wanted[name], name);
      if (before) assert.deepEqual(gen(dir), { 'server.ts': 'old\n' }, name); else assert.equal(existsSync(join(dir, '.gen')), false, name);
    }
  }
});
