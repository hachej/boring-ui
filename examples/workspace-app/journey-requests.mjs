import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { launch, pause, q, qa } from '@hachej/boring-testing/browser';
import { startWorkspaceApp } from './server.mjs';

const evidence = process.env.APP_EVIDENCE ?? '.cache/evidence/D141';
mkdirSync(evidence, { recursive: true });
const app = await startWorkspaceApp({ directory: mkdtempSync(join(tmpdir(), 'requests-')), scripted: true });
let browser;
const row = id => q(`[data-request="${id}"]`);
const textButton = text => `${qa('button')}.find(e => e.textContent === ${JSON.stringify(text)})`;
const listIds = `${qa('[data-request]')}.map(e => e.dataset.request)`;
const noOverflow = 'document.documentElement.scrollWidth <= innerWidth';
const panesFit = `${qa('[data-testid=requests-list-pane], [data-testid=requests-detail-pane]')}.filter(e => e.getBoundingClientRect().width > 0).every(e => e.scrollWidth <= e.clientWidth)`;
try {
  browser = await launch(`${app.url}?requests`, { evidence });
  const click = text => browser.click(textButton(text));
  const scheme = value => browser.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value }] });
  const shoot = async name => { for (const value of ['light', 'dark']) { await scheme(value); await pause(750); await browser.screenshot(`${name}-${value}.png`); } await scheme('light'); };
  await browser.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await browser.until('compact board', `!!${q('[data-boring=requests-board]')}`);
  assert.deepEqual(await browser.evaluate(listIds), ['D-902', 'D-901', 'D-908', 'D-904', 'D-912']);
  await shoot('desktop-compact');
  await click('Voir les 12 demandes');
  await browser.until('full board', `${q('[data-boring=requests-board]')}.dataset.mode === 'full'`);
  assert.equal(await browser.evaluate(`${q('[data-testid=requests-log]')}.textContent`), 'all');
  await browser.click(q('[data-filter=yours]'));
  assert.equal(await browser.evaluate(`${qa('[data-request]')}.length`), 2);
  await browser.click(row('D-902')); await click('Approuver');
  assert.equal(await browser.evaluate(`${q('[data-testid=requests-log]')}.textContent`), 'decide D-902 approve');
  await click('Plus tard');
  assert.equal(await browser.evaluate(`${q('[data-testid=requests-log]')}.textContent`), 'decide D-902 later');
  await browser.click(row('D-901'));
  await browser.type(q('textarea'), 'Un total'); await click('Répondre');
  assert.equal(await browser.evaluate(`${q('[data-testid=requests-log]')}.textContent`), 'answer D-901 Un total');
  await browser.click(q('[data-filter=active]'));
  await browser.type(q('input'), 'devis');
  assert.deepEqual(await browser.evaluate(listIds), ['D-905', 'D-902', 'D-901']);
  await browser.click(row('D-905'));
  assert.match(await browser.evaluate(`${q('[data-testid=requests-detail-pane]')}.textContent`), /D-905 créée/);
  assert.ok(await browser.evaluate(panesFit), 'list and detail have no horizontal overflow');
  await shoot('desktop-detail');
  await click('Parente · D-904');
  assert.equal(await browser.evaluate(`${q('[data-testid=requests-log]')}.textContent`), 'open D-904');
  await click('Essayer cette version');
  assert.equal(await browser.evaluate(`${q('[data-testid=requests-log]')}.textContent`), 'try D-904 preview');
  await browser.evaluate(`${q('input')}.focus(); ${q('input')}.select()`); await browser.press('Backspace');
  await click('Atelier Exemple — vitrine');
  assert.deepEqual(await browser.evaluate(listIds), ['D-912']);
  await click('Tous les dépôts');
  assert.equal(await browser.evaluate(`${qa('[data-request]')}.length`), 9);
  await browser.click(row('D-906'));
  assert.equal(await browser.evaluate(`!!${q('[data-testid=request-question]')}`), false);
  await click('Release permission');
  assert.equal(await browser.evaluate(`!!${q('[data-testid=request-question]')}`), true);
  await click('Release permission');
  assert.equal(await browser.evaluate(`!!${q('[data-testid=request-question]')}`), false);
  await click('D-903 → À essayer');
  await browser.until('host token announcement', `${q('[data-testid=requests-updates]')}.textContent === 'D-903 : à essayer'`);
  await click('FR / EN');
  assert.equal(await browser.evaluate(`${q('input')}.getAttribute('aria-label')`), 'Search requests');
  await shoot('desktop-english'); await click('FR / EN');
  await browser.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true }); await pause(300);
  const isVisible = selector => `${q(selector)}.getBoundingClientRect().width > 0`;
  assert.equal(await browser.evaluate(isVisible('[data-testid=requests-list-pane]')), false);
  assert.equal(await browser.evaluate(isVisible('[data-testid=requests-detail-pane]')), true);
  assert.ok(await browser.evaluate(noOverflow));
  await shoot('phone-detail');
  await click('Retour');
  assert.equal(await browser.evaluate('document.activeElement.dataset.request'), 'D-906', 'Back restores keyboard focus after the list is visible');
  assert.equal(await browser.evaluate(isVisible('[data-testid=requests-list-pane]')), true);
  assert.equal(await browser.evaluate(isVisible('[data-testid=requests-detail-pane]')), false);
  await browser.evaluate(`${qa('[data-request]')}[0].focus()`);
  await browser.press('ArrowDown');
  assert.equal(await browser.evaluate(`document.activeElement.dataset.request`), await browser.evaluate(`${qa('[data-request]')}[1].dataset.request`));
  await browser.press('Enter');
  await browser.until('keyboard opens detail', isVisible('[data-testid=requests-detail-pane]'));
  assert.ok(await browser.evaluate(noOverflow));
  await click('Retour');
  assert.ok(await browser.evaluate(panesFit), 'phone panes have no horizontal overflow');
  await shoot('phone-list');
  await click('Compact'); await shoot('phone-compact');
  assert.ok(await browser.evaluate(noOverflow));
  assert.deepEqual(browser.problems, [], 'no browser errors');
  console.log(`PASS requests: compact, full, search, links, answers, decisions, release gate, keyboard, host updates; screenshots: ${evidence}`);
} finally { await browser?.close(); await app.close(); }
